def _flat(v):
    return isinstance(v, (list, tuple, dict, set, np.ndarray))


def fingerprint(df: pd.DataFrame) -> dict:
    d = df.copy()
    for c in d.columns:
        if d[c].map(_flat).any():
            d[c] = d[c].map(str)
    h = int(pd.util.hash_pandas_object(d, index=True).astype("uint64").sum() % (2 ** 63))
    out = {"shape": list(df.shape), "columns": list(df.columns),
           "dtypes": [str(t) for t in df.dtypes], "hash": h}
    for col in ("track_id", "artist_display", "artist_name", "release_year", "decade"):
        if col in df.columns:
            out[col] = [None if pd.isna(v) else v for v in df[col].head(4).tolist()]
    return out


