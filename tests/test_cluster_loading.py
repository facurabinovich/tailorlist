def to_frame(rows: list[dict]) -> pd.DataFrame:
    df = pd.DataFrame(rows).rename(columns={
        "id": "track_id", "name": "track_name", "artists": "artist_name",
        "popularity": "popularity_raw", "album": "album_name",
        "duration_ms": "duration_raw"})
    df["release_year"] = parse_release_year(df["release_date"])
    df["decade"] = (df["release_year"] // 10 * 10).where(df["release_year"].notna())
    return add_artist_display(df)


def fc_cluster_frame() -> pd.DataFrame:
    """What db.load_cluster_data returns: enriched rows, with a duplicated id on purpose."""
    base = to_frame(COLL["enriched"])[_CLUSTER_COLS]
    return pd.concat([base, base.iloc[:3]], ignore_index=True)


def fc_unmatched_frame() -> pd.DataFrame:
    return to_frame(COLL["skipped"])


def fc_grouping_frame() -> pd.DataFrame:
    return to_frame(COLL["enriched"] + COLL["skipped"] + COLL["failed"])


