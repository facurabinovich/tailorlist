"""Characterization tests for core/export.py.

Expected strings were generated by running the original inline expressions
from ui/export.py before they were extracted.
"""

import pytest

from core.export import spotify_track_urls, spotlistr_lines

TRACKS = [
    {"id": "a1", "name": "Song One", "artists": "Artist A"},
    {"id": "b2", "name": "Duet", "artists": "Artist B, Artist C"},
    {"id": "c3", "name": "Rock & Roll", "artists": "Simon & Garfunkel"},
    {"id": "d4", "name": "Canción Ñandú", "artists": "  Beyoncé , Jay-Z"},
    {"id": "a1", "name": "Song One", "artists": "Artist A"},
    {"id": "e5", "name": "No Artist Key"},
    {"id": "f6", "artists": "Only Artist"},
    {"id": "g7", "name": "Empty Artist", "artists": ""},
]


def test_spotlistr_lines_characterization():
    assert spotlistr_lines(TRACKS) == (
        "Artist A - Song One\n"
        "Artist B - Duet\n"
        "Simon & Garfunkel - Rock & Roll\n"
        "Beyoncé - Canción Ñandú\n"
        "Artist A - Song One\n"
        " - No Artist Key\n"
        "Only Artist - \n"
        " - Empty Artist"
    )


def test_spotify_track_urls_characterization():
    base = "https://open.spotify.com/track/"
    assert spotify_track_urls(TRACKS) == "\n".join(
        base + i for i in ["a1", "b2", "c3", "d4", "a1", "e5", "f6", "g7"]
    )


def test_empty_list():
    assert spotlistr_lines([]) == ""
    assert spotify_track_urls([]) == ""


def test_none_artist_raises_like_original():
    with pytest.raises(AttributeError):
        spotlistr_lines([{"name": "x", "artists": None}])


def test_missing_id_raises_like_original():
    with pytest.raises(KeyError):
        spotify_track_urls([{"name": "x"}])
