def test_release_date_to_decade():
    assert [release_date_to_decade(x) for x in RD_CASES] == EXPECTED["rd"]


@pytest.mark.parametrize("key", list(EXPECTED["cat"]), ids=str)
def test_group_by_category(frame, key):
    before = frame.copy()
    clustered, unmatched = group_by_category(frame, *key)
    exp = EXPECTED["cat"][key]
    assert summarize(clustered) == exp["clustered"]
    assert summarize(unmatched) == exp["unmatched"]
    pd.testing.assert_frame_equal(frame, before)  # input not mutated
    assert list(frame.columns) == EXPECTED["input_cols"]


@pytest.mark.parametrize("key", list(EXPECTED["sgl"]), ids=str)
def test_group_by_specific_genres(frame, key):
    i, by_decade = key
    before = frame.copy()
    out = group_by_specific_genres(frame, SGL_SELECTIONS[i], by_decade)
    assert summarize(out) == EXPECTED["sgl"][key]
    pd.testing.assert_frame_equal(frame, before)


