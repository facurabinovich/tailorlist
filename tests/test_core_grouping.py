def build_frame(coll, rd_to_decade):
    rows, seen = [], set()
    for t in coll["enriched"] + coll["skipped"] + coll["failed"]:
        if t.get("id") in seen:
            continue
        seen.add(t.get("id"))
        rd = t.get("release_date", "") or ""
        rows.append({
            "track_id": t.get("id", ""), "track_name": t.get("name", ""),
            "artist_name": ", ".join(t["artists"]) if isinstance(t.get("artists"), list) else t.get("artists", ""),
            "release_year": rd[:4] if rd else "",
            "decade": rd_to_decade(rd),
            "artist_genres": t.get("artist_genres", ""),
            "playlist_name": t.get("playlist_name", ""),
            "energy": t.get("energy"),
        })
    df = pd.DataFrame(rows)
    # tracks without genres: blank, None and whitespace variants
    df.loc[df.index[:3], "artist_genres"] = ["", None, "   "]
    return df


def _sha(obj):
    return hashlib.sha256(json.dumps(obj).encode()).hexdigest()


def summarize(df):
    if df is None or df.empty:
        return {"shape": tuple(df.shape), "empty": True}
    if "cluster_name" not in df.columns:
        return {"shape": tuple(df.shape), "columns": list(df.columns), "ids_sha": _sha(sorted(map(str, df["track_id"])))}
    names = df["cluster_name"].value_counts().sort_index()
    pairs = sorted((str(t), n) for t, n in zip(df["track_id"], df["cluster_name"]))
    idx = sorted((n, int(c)) for n, c in set(zip(df["cluster_name"], df["cluster"])))
    return {
        "shape": tuple(df.shape), "columns": list(df.columns),
        "counts": {k: int(v) for k, v in names.items()},
        "map_sha": _sha(pairs), "idx": idx,
        "pc_zero": bool((df["PC1"] == 0).all() and (df["PC2"] == 0).all()),
        "index_sha": _sha([int(i) for i in df.index]),
    }


