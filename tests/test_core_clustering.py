    dfc, name_map, cents, v1, v2, scaler, l1, l2 = tup
    exp = EXPECTED["k"][k]
    labels = dict(zip(dfc["track_id"], dfc["cluster"].astype(int)))
    assert _sha(labels) == exp["labels_sha"]
    assert list(labels.items())[:6] == [tuple(x) for x in exp["labels_head"]]
    assert name_map == exp["name_map"]
    assert cents.round(6).values.tolist() == exp["centroids"]
    assert [round(v1, 6), round(v2, 6)] == exp["var"]
    assert [l1, l2] == exp["pc"]
    assert dfc["PC1"].round(6).head(5).tolist() == exp["pc1_head"]
    assert dfc["PC2"].round(6).head(5).tolist() == exp["pc2_head"]
    assert scaler.mean_.round(6).tolist() == exp["scaler_mean"]
    assert list(dfc.columns) == exp["cols"]


